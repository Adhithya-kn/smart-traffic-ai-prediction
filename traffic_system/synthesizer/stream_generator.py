"""
traffic_system/synthesizer/stream_generator.py - Synthetic Telemetry & Incident Stream Synthesizer
Generates calibrated spatio-temporal perturbations, monsoon deluge surges, and shockwave cascades
across Bengaluru's 24 arterial corridors for resilience stress-testing.

Explicit Provenance Standard:
All data generated by this module is explicitly labelled as synthetic simulation data.
Scenario generation is deterministic and reproducible via explicit random seeds.
"""

import math
import random
import threading
from typing import Dict, Any, List, Optional

from traffic_system.core.time_utils import now_iso
from traffic_system.core.road_registry import get_road_name


SCENARIO_CONFIGS = {
    "monsoon_flood": {
        "title": "Monsoon Deluge & Urban Waterlogging",
        "description": "Simulates 65mm/hr convective precipitation leading to surface water pooling and severe hydrodynamic speed reduction.",
        "speed_factor_range": (0.40, 0.65),
        "volume_factor_range": (0.85, 1.15),
        "vulnerable_zones": ["Indiranagar", "Hebbal North", "Koramangala", "Electronic City South"],
        "default_intensity": 0.80
    },
    "bottleneck_cascade": {
        "title": "Arterial Bottleneck & Shockwave Spillback",
        "description": "Simulates primary lane blockage triggering backwards-propagating stop-and-go shockwaves across adjacent corridors.",
        "speed_factor_range": (0.30, 0.55),
        "volume_factor_range": (1.10, 1.45),
        "vulnerable_zones": ["Downtown Core", "Financial District", "Indiranagar"],
        "default_intensity": 0.85
    },
    "festival_surge": {
        "title": "Metropolitan Festival & Shopping Surge",
        "description": "Simulates 40-70% non-linear vehicle volume spikes around commercial corridors and transit hubs.",
        "speed_factor_range": (0.50, 0.75),
        "volume_factor_range": (1.30, 1.80),
        "vulnerable_zones": ["M.G. Road CBD", "Jayanagar", "Koramangala", "Whitefield"],
        "default_intensity": 0.70
    },
    "sensor_blackout": {
        "title": "IoT Edge Sensor & GPS Telemetry Blackout",
        "description": "Simulates intermittent packet loss and telemetry dropout, testing machine learning heuristic inference fallback.",
        "speed_factor_range": (0.80, 1.05),
        "volume_factor_range": (0.85, 1.10),
        "vulnerable_zones": ["Suburban North", "Yeshwanthpur West", "Industrial East"],
        "default_intensity": 0.60
    }
}


class StreamSynthesizer:
    """Subsystem for synthesizing dynamic traffic scenarios and stress-testing the live grid."""
    _instance: Optional["StreamSynthesizer"] = None
    _lock = threading.Lock()

    @classmethod
    def get_instance(cls) -> "StreamSynthesizer":
        with cls._lock:
            if cls._instance is None:
                cls._instance = StreamSynthesizer()
            return cls._instance

    def get_available_scenarios(self) -> List[Dict[str, Any]]:
        """Returns catalogue of supported simulation scenarios with metadata."""
        return [
            {
                "type": key,
                "title": cfg["title"],
                "description": cfg["description"],
                "default_intensity": cfg["default_intensity"],
                "vulnerable_zones": cfg["vulnerable_zones"],
                "speed_factor_range": cfg["speed_factor_range"],
                "volume_factor_range": cfg["volume_factor_range"],
                "is_synthetic": True,
                "provenance": "Synthetic Simulation Catalog"
            }
            for key, cfg in SCENARIO_CONFIGS.items()
        ]

    def generate_synthetic_stream(
        self,
        scenario_type: str = "monsoon_flood",
        intensity: float = 0.75,
        target_zones: Optional[List[str]] = None,
        topology: Optional[Dict[str, Any]] = None,
        random_seed: Optional[int] = None
    ) -> Dict[str, Any]:
        """
        Executes calibrated synthetic perturbation against corridor network topology.
        Returns detailed before-and-after corridor metrics and grid stress indices.

        Scenario Generation & Reproducibility:
        - scenario_type: Preset simulation archetype ('monsoon_flood', 'bottleneck_cascade', 'festival_surge', 'sensor_blackout').
        - intensity: Perturbation severity factor clamped between 0.10 (minor) and 1.00 (catastrophic).
        - random_seed: Explicit PRNG seed for exact reproducibility. If None, derived deterministically from intensity and scenario name.
        - Provenance: All output payloads are explicitly labeled with `is_synthetic: True` and simulated provenance.
        """
        clean_type = str(scenario_type).lower().strip()
        if clean_type not in SCENARIO_CONFIGS:
            clean_type = "monsoon_flood"

        cfg = SCENARIO_CONFIGS[clean_type]
        clamped_intensity = max(0.10, min(1.0, float(intensity)))

        # Load topology from predictor if not provided
        if not topology:
            from app.server import TrafficAppServer
            if TrafficAppServer.predictor and TrafficAppServer.predictor.topology:
                topology = TrafficAppServer.predictor.topology
            else:
                topology = {}

        vulnerable = set(cfg["vulnerable_zones"])
        if target_zones:
            filter_zones = set(target_zones)
        else:
            filter_zones = None

        corridor_results = []
        total_speed_drop = 0.0
        total_volume_surge = 0.0
        severe_count = 0
        high_count = 0

        # Deterministic PRNG seed resolution for full scenario reproducibility
        if random_seed is not None:
            effective_seed = int(random_seed)
        else:
            effective_seed = int(clamped_intensity * 10000) + (len(clean_type) * 79) + 42

        rng = random.Random(effective_seed)

        for road_id, info in topology.items():
            zone = info.get("city_zone", "Metropolitan")
            if filter_zones and zone not in filter_zones:
                continue

            base_spd = float(info.get("avg_speed", 32.0))
            base_vol = float(info.get("avg_volume", 1450.0))
            capacity = float(info.get("capacity", 3500.0))

            is_affected = (zone in vulnerable) or (rng.random() < clamped_intensity)

            if is_affected:
                # Apply scenario degradation factor
                min_sf, max_sf = cfg["speed_factor_range"]
                spd_factor = max_sf - (clamped_intensity * (max_sf - min_sf)) + (rng.uniform(-0.05, 0.05))
                spd_factor = max(0.20, min(1.0, spd_factor))

                min_vf, max_vf = cfg["volume_factor_range"]
                vol_factor = 1.0 + (clamped_intensity * (max_vf - 1.0)) + (rng.uniform(-0.05, 0.08))
                vol_factor = max(0.50, vol_factor)
            else:
                spd_factor = 1.0 + rng.uniform(-0.05, 0.05)
                vol_factor = 1.0 + rng.uniform(-0.03, 0.04)

            sim_spd = round(base_spd * spd_factor, 1)
            sim_vol = int(base_vol * vol_factor)
            utilization = round((sim_vol / max(capacity, 1.0)) * 100.0, 1)

            # Classify simulated state
            if utilization >= 90.0 or sim_spd <= 12.0:
                sim_cong = "Severe"
                severe_count += 1
            elif utilization >= 70.0 or sim_spd <= 20.0:
                sim_cong = "High"
                high_count += 1
            elif utilization >= 40.0:
                sim_cong = "Moderate"
            else:
                sim_cong = "Low"

            spd_delta = round(sim_spd - base_spd, 1)
            vol_delta = sim_vol - int(base_vol)

            total_speed_drop += max(0.0, -spd_delta)
            total_volume_surge += max(0, vol_delta)

            corridor_results.append({
                "road_id": road_id,
                "road_name": get_road_name(road_id),
                "city_zone": zone,
                "is_synthetic": True,
                "provenance": "Synthetic Stress-Test Telemetry",
                "baseline": {
                    "speed_kmh": base_spd,
                    "volume_vph": int(base_vol),
                    "congestion": info.get("common_congestion", "Moderate"),
                    "provenance": "Empirical Baseline"
                },
                "simulated": {
                    "speed_kmh": sim_spd,
                    "volume_vph": sim_vol,
                    "capacity_utilization_pct": utilization,
                    "congestion": sim_cong,
                    "is_synthetic": True,
                    "provenance": "Synthetic Simulation"
                },
                "deltas": {
                    "speed_delta_kmh": spd_delta,
                    "volume_delta_vph": vol_delta
                },
                "is_critical": sim_cong in ("High", "Severe")
            })

        n_evaluated = max(len(corridor_results), 1)
        avg_speed_drop = round(total_speed_drop / n_evaluated, 1)
        grid_stress_index = min(100.0, round(((severe_count * 3.5 + high_count * 1.8) / n_evaluated) * 100.0, 1))

        return {
            "scenario_id": f"SYN_{clean_type.upper()[:4]}_{rng.randint(1000, 9999)}",
            "scenario_type": clean_type,
            "scenario_title": cfg["title"],
            "intensity": clamped_intensity,
            "random_seed": effective_seed,
            "is_synthetic": True,
            "is_simulated": True,
            "provenance": "Synthetic Telemetry Generator",
            "data_provenance": "Synthetic Stress-Test Telemetry",
            "disclaimer": "Generated streams are synthetic stress-test simulations and do not represent physical sensor readings.",
            "scenario_generation_metadata": {
                "methodology": "Spatio-temporal perturbation model with hydrodynamic flow degradation",
                "scenario_type": clean_type,
                "scenario_title": cfg["title"],
                "scenario_description": cfg["description"],
                "intensity": clamped_intensity,
                "random_seed": effective_seed,
                "is_deterministic": True,
                "speed_factor_range": cfg["speed_factor_range"],
                "volume_factor_range": cfg["volume_factor_range"],
                "vulnerable_zones": cfg["vulnerable_zones"],
                "generation_engine": "StreamSynthesizer v2.0"
            },
            "timestamp": now_iso(),
            "corridors_evaluated": len(corridor_results),
            "network_impact": {
                "grid_stress_index": grid_stress_index,
                "avg_speed_drop_kmh": avg_speed_drop,
                "total_volume_surge_vph": int(total_volume_surge),
                "severe_corridors_count": severe_count,
                "high_corridors_count": high_count,
                "stable_corridors_count": len(corridor_results) - (severe_count + high_count)
            },
            "corridors": sorted(corridor_results, key=lambda c: (c["simulated"]["congestion"] != "Severe", c["simulated"]["speed_kmh"]))
        }


def get_stream_synthesizer() -> StreamSynthesizer:
    return StreamSynthesizer.get_instance()
